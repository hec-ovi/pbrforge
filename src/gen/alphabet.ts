/** Glyph box, tracking and cap height, in box units. */
export const BOX = 6;
export const ADVANCE = 7.6;
export const CAP = 10;

/** Distance from a point in box units to the nearest stroke centreline of a glyph. */
export function glyphDistance(char: string, x: number, y: number): number {
  const polys = GLYPHS[char];
  if (!polys) return Infinity;
  let best = Infinity;
  for (const poly of polys) {
    for (let i = 1; i < poly.length; i++) {
      best = Math.min(best, segmentDistance(x, y, poly[i - 1], poly[i]));
    }
    if (poly.length === 1) best = Math.min(best, Math.hypot(x - poly[0][0], y - poly[0][1]));
  }
  return best;
}

function segmentDistance(x: number, y: number, a: [number, number], b: [number, number]): number {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const length = dx * dx + dy * dy;
  const t = length === 0 ? 0 : Math.min(1, Math.max(0, ((x - a[0]) * dx + (y - a[1]) * dy) / length));
  return Math.hypot(x - (a[0] + dx * t), y - (a[1] + dy * t));
}
